def supported_lang(lang: str | None) -> str:
    if not lang:
        return "de"
    lang = lang.strip().lower()
    return lang if lang in TRANSLATIONS else "de"


def t(translations: dict[str, dict[str, str]], lang: str, key: str, **kwargs: Any) -> str:
    text = translations[lang].get(key) or translations["de"].get(key) or key
    for k, v in kwargs.items():
        text = text.replace("{" + k + "}", str(v))
    return text

